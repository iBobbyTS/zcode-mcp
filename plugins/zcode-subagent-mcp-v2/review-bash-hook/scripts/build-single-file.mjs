#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.dirname(here);
const corePath = path.join(root, 'lib', 'readonly-bash-policy.mjs');
const outputPath = path.join(root, 'single-file', 'check-bash-status.mjs');
const core = fs.readFileSync(corePath, 'utf8').replace(/^export\s+/gmu, '');
const wrapper = `\n\nlet __raw = '';\nprocess.stdin.setEncoding('utf8');\nfor await (const __chunk of process.stdin) __raw += __chunk;\ntry {\n  const __input = JSON.parse(__raw);\n  const __evaluated = evaluateHookInput(__input);\n  process.stdout.write(JSON.stringify(createHookOutput(__evaluated)) + '\\n');\n} catch (__error) {\n  const __message = __error instanceof Error ? __error.message : String(__error);\n  process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: 'zcode-readonly-bash/v1.0.0 hook_internal_error: ' + __message.slice(0, 300) } }) + '\\n');\n}\n`;
const banner = `#!/usr/bin/env node\n// Generated by scripts/build-single-file.mjs. Edit lib/readonly-bash-policy.mjs instead.\n`;
fs.writeFileSync(outputPath, banner + core + wrapper, { mode: 0o755 });
fs.chmodSync(outputPath, 0o755);
console.log(outputPath);
